/**
 * 測る道具の乱数（`src/sim/`。**本番からは呼ばない**）。
 *
 * ⚠ **種を渡せること。同じ種なら同じ結果になること。**これが測り直しの土台で、
 *   数値を動かしたときに「変わったのは調整のせいか、乱数のせいか」を分ける唯一の手段になる。
 *
 * ⚠ **遊びの数値ではない。**ここに調整の余地は無いので、`taxonomy/` の定数とは別物として扱う。
 */

/** mulberry32。32bit の種から 0以上1未満を返す */
export function makeRng(seed: number): () => number {
  let a = (Math.floor(seed) >>> 0) || 1
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    // ⚠ **2^32 を数で書かない。**`goal.test.ts` が「百万以上の数の別書き」を見ている
    return ((t ^ (t >>> 14)) >>> 0) / (2 ** 32)
  }
}
