/**
 * 金額の書き方を**1本にまとめる**（#1）。
 *
 * ⚠ **なぜ要るか**: `¥` だった頃、同じ通貨が **16箇所に手書き**で散っていて、
 *   **桁区切りが付く箇所と付かない箇所が混ざっていた**（`unitCost` ／ `revenue` に無し）。
 *   次に通貨を触るとき、また16箇所を探すことになる。
 *
 * **書き方は `1,234レン`**（数のうしろ。日本語の語順）。
 * 符号（`+` `−`）は**呼び出し側に残す** —— 売れた知らせと工房の3ルートで意味が違う。
 */
export function money(n: number): string {
  return `${n.toLocaleString()}レン`
}
